#!/usr/bin/env python3
"""Generate apps/v4_0-metric-api/dop853_coeffs.cuh from SciPy's DOP853 tableau (scipy/integrate/_ivp/dop853_coefficients.py,
itself from Hairer's dop853.f; Hairer, Norsett & Wanner, Solving ODEs I, 2nd ed., sec. II.10). Writing ~100 constants by hand
invites typos; the generated header is checked by the order test in --selftest (O3).

    uv run --with scipy python tools/gen_dop853.py > apps/v4_0-metric-api/dop853_coeffs.cuh
"""
import scipy
from scipy.integrate._ivp import dop853_coefficients as d

N = d.N_STAGES  # 12


def lit(x):
    return repr(float(x))


out = [
    "#pragma once",
    f"// GENERATED by tools/gen_dop853.py from SciPy {scipy.__version__} (dop853_coefficients.py, Hairer's dop853.f). Do not edit by hand.",
    "// DOP853: 12 stages, order 8, error estimators of order 5 (E5) and 3 (E3); K[12] = f(t + h, y_new) enters the estimators only.",
    "namespace bk::dop853 {",
    f"constexpr int kStages = {N};",
]
rows = []
for i in range(N):
    rows.append("  {" + ", ".join(lit(d.A[i, j]) for j in range(N)) + "}")
out.append(f"__device__ constexpr double A[{N}][{N}] = {{\n" + ",\n".join(rows) + "};")
out.append(f"__device__ constexpr double B[{N}] = {{" + ", ".join(lit(x) for x in d.B) + "};")
out.append(f"__device__ constexpr double C[{N}] = {{" + ", ".join(lit(x) for x in d.C[:N]) + "};")
out.append(f"__device__ constexpr double E3[{N + 1}] = {{" + ", ".join(lit(x) for x in d.E3) + "};")
out.append(f"__device__ constexpr double E5[{N + 1}] = {{" + ", ".join(lit(x) for x in d.E5) + "};")
out.append("}  // namespace bk::dop853")
print("\n".join(out))
