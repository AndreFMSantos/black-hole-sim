Request draw(State& st, kcuda::Params& p, Camera& cam, std::string& observer, bool cinematic, const Perf& perf, double dt) {
  Request rq;
  advance(st, p, cam, observer, dt, rq);
  if (!st.show) return rq;
  ImGui::SetNextWindowPos(ImVec2(10, 10), ImGuiCond_FirstUseEver);
  ImGui::SetNextWindowSize(ImVec2(400, 720), ImGuiCond_FirstUseEver);
  if (!ImGui::Begin("black-hole-sim (F1 show/hide)", &st.show)) { ImGui::End(); return rq; }
  ImGui::Text("%.0f fps | %.1f ms/sample | sample %d", perf.fps, perf.ms, perf.samples);
  std::string why; const Badge b = classify(p, cinematic, why);
  ImGui::TextColored(badge_colour(b), "[%s]", badge_name(b)); ImGui::SameLine(); ImGui::TextWrapped("%s", why.c_str());
  ImGui::Separator();
  { const bool can_fly = !p.wormhole && p.charge == 0 && p.lambda == 0;  // the ship is a Kerr geodesic pilot
    ImGui::BeginDisabled(!can_fly);
    if (ImGui::Button("Fly the ship (F)")) rq.toggle_flight = true;
    ImGui::EndDisabled();
    if (!can_fly && ImGui::IsItemHovered(ImGuiHoveredFlags_AllowWhenDisabled)) ImGui::SetTooltip("Flight is only defined for Kerr (and Schwarzschild).\nIn the wormhole use the mouse wheel, the position slider or 'travel through the throat'."); }
  ImGui::SameLine(); if (ImGui::Button("Save snapshot")) rq.want_screenshot = true;
  ImGui::TextDisabled("Fly: thrusters on a free-falling Kerr geodesic. Snapshot: snapshots/bhs_NNN.png + .txt (the command that reproduces it).");
  ImGui::Separator();

  if (ImGui::CollapsingHeader("Versions and variants", ImGuiTreeNodeFlags_DefaultOpen)) {
    const char* last = "";
    for (int i = 0; i < kN; ++i) {
      if (std::string(kScenarios[i].group) != last) { last = kScenarios[i].group; ImGui::TextDisabled("%s", last); }
      ImGui::PushStyleColor(ImGuiCol_Text, badge_colour(kScenarios[i].badge));
      char lab[160]; std::snprintf(lab, sizeof lab, "%s##sc%d", kScenarios[i].title, i);
      const bool sel = ImGui::Selectable(lab, st.scenario == i);
      ImGui::PopStyleColor();
      if (ImGui::IsItemHovered()) ImGui::SetTooltip("%s\n[%s]", kScenarios[i].note, badge_name(kScenarios[i].badge));
      if (sel) { st.scenario = i; rq.apply_setup = true; rq.setup = make_setup(i, p); }
    }
  }

  if (p.wormhole && !st.sky2_note.empty()) ImGui::TextColored(ImVec4(1.f, 0.45f, 0.35f, 1.f), "%s", st.sky2_note.c_str());

  if (ImGui::CollapsingHeader("Black hole", ImGuiTreeNodeFlags_DefaultOpen)) {
    int kind = p.wormhole ? 3 : p.lambda > 0 ? 2 : p.charge > 0 ? 1 : 0;
    const char* kinds[] = {"Kerr", "Kerr-Newman / Reissner-Nordstrom", "Schwarzschild-de Sitter", "Wormhole"};
    int nk = kind;
    if (ImGui::Combo("Metric", &nk, kinds, 4) && nk != kind) {
      p.wormhole = nk == 3; p.charge = nk == 1 ? 0.5 : 0; p.lambda = nk == 2 ? 0.01 : 0;
      if (nk == 3) { p.nodisk = true; p.wh_ellis = false; p.wh_rho = 1; p.wh_a = 0.005; p.wh_M = 0.05 / 1.42953; p.wh_lc = 4; p.fov_deg = 50; cam.dist = 4; }
      if (nk == 2) { p.a = 0; p.nodisk = true; cam.dist = std::min(cam.dist, 8.0); }
      p.rin = -1; p.nt = true; p.hr = 0; p.model = 0;
    }
    float a = float(p.a);
    if (!p.wormhole && ImGui::SliderFloat("spin a", &a, 0.f, 0.9999f, "%.4f")) { p.a = a; if (p.lambda > 0) p.a = 0; }
    if (p.charge > 0 || nk == 1) {
      float q = float(p.charge);
      if (ImGui::SliderFloat("charge Q", &q, 0.01f, 1.5f, "%.3f")) p.charge = q;
      const bool naked = p.a * p.a + p.charge * p.charge >= 1.0;
      if (naked) { p.nt = false; if (p.rin < 0) p.rin = 6; ImGui::TextColored(ImVec4(0.95f, 0.45f, 0.35f, 1), "a^2 + Q^2 >= 1: naked singularity (Newtonian disk, r_in = %.1f)", p.rin); }
      else p.rin = -1;
    }
    if (p.lambda > 0) {
      float l = float(p.lambda);
      if (ImGui::SliderFloat("Lambda", &l, 1e-4f, 0.11f, "%.4f", ImGuiSliderFlags_Logarithmic)) p.lambda = l;
      p.nt = false; if (p.rin < 0) p.rin = 6;
    }
    if (p.wormhole) {
      bool ell = p.wh_ellis; if (ImGui::Checkbox("Ellis (otherwise: Interstellar)", &ell)) p.wh_ellis = ell;
      float lc = float(p.wh_lc);
      if (ImGui::SliderFloat("position l (rho); < 0: far side", &lc, -60.f, 60.f, "%.2f", ImGuiSliderFlags_Logarithmic)) { p.wh_lc = lc; cam.dist = std::max(0.1, std::fabs(double(lc))); }
      ImGui::Checkbox("travel through the throat", &st.wh_travel); ImGui::SameLine(); ImGui::SetNextItemWidth(110); ImGui::SliderFloat("beta (v/c)", &st.wh_speed, 0.05f, 0.95f, "%.2f");
    }
  }

  if (ImGui::CollapsingHeader("Disk")) {
    const bool restricted = p.wormhole || p.charge > 0 || p.lambda > 0;
    int dk = p.nodisk ? 0 : p.lp_h > 0 ? 9 : p.model == 5 ? 8 : p.model == 4 ? 7 : p.model == 3 ? 6 : p.model == 2 ? 5 : p.model == 1 ? 4 : p.hr > 0 ? 3 : p.nt ? 1 : 2;
    const char* dks[] = {"None", "Thin Novikov-Thorne", "Thin Newtonian", "Thick (layer)", "Radio: torus", "Radio: GRMHD", "Radio: RIAF (parametric)", "Spherical inflow (bolometric)", "Jet walls (dual cone)", "X-ray: lamppost reflection (bolometric)"};
    int nd = dk;
    if (restricted) ImGui::TextDisabled("Greyed-out disks are not defined for this metric (hover for the reason).");
    const kcuda::MetricKind mk = kcuda::metric_kind(p);
    const kcuda::DiskKind dkind[] = {kcuda::DiskKind::None, kcuda::DiskKind::NovikovThorne, kcuda::DiskKind::Newtonian, kcuda::DiskKind::Thick, kcuda::DiskKind::Torus, kcuda::DiskKind::Grmhd, kcuda::DiskKind::Riaf, kcuda::DiskKind::Spherical, kcuda::DiskKind::JetCones, kcuda::DiskKind::Lamppost};
    bool picked = false;
    if (ImGui::BeginCombo("Type", dks[dk])) {  // unsupported combinations (combos.hpp) are shown disabled, with the reason as a tooltip
      for (int i = 0; i < 10; ++i) {
        const char* why = ""; const bool ok = kcuda::disk_supported(mk, dkind[i], &why);
        ImGui::BeginDisabled(!ok);
        if (ImGui::Selectable(dks[i], i == dk)) { nd = i; picked = true; }
        ImGui::EndDisabled();
        if (!ok && ImGui::IsItemHovered(ImGuiHoveredFlags_AllowWhenDisabled)) ImGui::SetTooltip("%s", why);
      }
      ImGui::EndCombo();
    }
    if (picked && nd != dk) {
      p.lp_h = 0.0;  // only the lamppost entry (below) turns it on
      p.nodisk = nd == 0; p.model = nd == 4 ? 1 : nd == 5 ? 2 : nd == 6 ? 3 : nd == 7 ? 4 : nd == 8 ? 5 : 0; p.nt = nd == 1; p.hr = nd == 3 ? 0.06 : 0; if (nd == 3) { p.tau = 4; p.flare = 0.15; p.nt = true; }
      if (nd == 9) { p.nodisk = false; p.model = 0; p.hr = 0; p.nt = false; p.lp_h = 6.0; p.lp_async = true; p.lp_lo = -4.0; p.lp_hi = 1.0; p.rout = std::max(p.rout, 30.0); p.fov_deg = 40; cam.dist = std::max(cam.dist, 70.0); }
      else if (nd == 8) { p.nodisk = false; p.fov_deg = 24; cam.dist = std::max(cam.dist, 100.0); p.prec = kcuda::Precision::Float; p.tol = 2e-5; p.nt = false; }
      else if (nd == 7) { p.nodisk = false; p.fov_deg = 24; cam.dist = std::max(cam.dist, 100.0); p.prec = kcuda::Precision::Float; p.tol = 2e-5; p.nt = false; p.sph_narayan = false; p.sph_rin = 0; }
      else if (nd >= 4) { p.nodisk = false; p.fov_deg = 16; cam.dist = std::max(cam.dist, 150.0); p.mbh = 6.5e9; p.nu_ghz = 230; p.tb_lo = 8.5; p.tb_hi = 11; p.prec = kcuda::Precision::Float; p.tol = 2e-5; p.nt = false;
        if (nd == 4) { p.torus_rin = 7; p.torus_rmax = 12; p.ne0 = 3e4; p.plasma_beta = 3; p.theta_e_max = 20; } else if (nd == 6) { p.rin = -1; p.ne0 = 8e3; p.plasma_beta = 10; p.theta_e_max = 12; p.riaf_pn = 1.1; p.riaf_pt = 0.84; p.riaf_hr = 0.3; p.riaf_xi = 0.5; p.riaf_rout = 40; } else { p.electrons = 1; p.emission = 1; p.munit = 7.361e24; p.grmhd_rcap = 30; p.grmhd_sigma_cut = 1; } }
    }
    if (!p.nodisk && p.model == 0) { float ro = float(p.rout); if (ImGui::SliderFloat("outer radius", &ro, 8.f, 80.f)) p.rout = ro; }
    if (p.hr > 0) { float h = float(p.hr), t = float(p.tau), f = float(p.flare); ImGui::SliderFloat("H/r", &h, 0.01f, 0.2f); ImGui::SliderFloat("tau", &t, 0.5f, 10.f); ImGui::SliderFloat("flare", &f, 0.f, 0.5f); p.hr = h; p.tau = t; p.flare = f; }
    if (p.model == 3) {  // parametric RIAF: every number is a free model parameter
      float pn = float(p.riaf_pn), pt = float(p.riaf_pt), hr = float(p.riaf_hr), xi = float(p.riaf_xi);
      ImGui::SliderFloat("n_e ~ r^-p", &pn, 0.5f, 2.f); ImGui::SliderFloat("Theta_e ~ r^-q", &pt, 0.f, 1.5f); ImGui::SliderFloat("H/r", &hr, 0.05f, 0.6f); ImGui::SliderFloat("Omega / Omega_K", &xi, 0.1f, 1.f);
      p.riaf_pn = pn; p.riaf_pt = pt; p.riaf_hr = hr; p.riaf_xi = xi;
    }
    if (p.lp_h > 0) {  // X-ray lamppost: the corona is a point on the axis at height h; h is applied when the slider is released; the emissivity table (~1.5 s) is built in the background
      float lo = float(p.lp_lo), hi = float(p.lp_hi);
      const double rh = 1.0 + std::sqrt(std::max(0.0, 1.0 - p.a * p.a));
      static float h_ui = 6.f; static bool h_drag = false;
      if (!h_drag) h_ui = float(p.lp_h);
      ImGui::SliderFloat("source height h [M]", &h_ui, float(rh) + 0.1f, 40.f, "%.2f", ImGuiSliderFlags_Logarithmic);
      h_drag = ImGui::IsItemActive();
      if (ImGui::IsItemDeactivatedAfterEdit()) p.lp_h = std::max<double>(h_ui, rh + 0.05);
      ImGui::Checkbox("light the plunging region (gas inside the ISCO)", &p.lp_plunge);
      float gm = float(p.lp_gamma), rf = float(p.lp_refl);
      ImGui::SliderFloat("photon index Gamma (2 = bolometric)", &gm, 1.2f, 3.0f, "%.2f"); ImGui::SliderFloat("reflection fraction (0 = geometric)", &rf, 0.f, 5.f, "%.2f");
      p.lp_gamma = gm; p.lp_refl = rf;
      p.lp_async = true;  // the table of the new (a, h) is built in the background; the old one is drawn meanwhile
      ImGui::SliderFloat("log10 I min##lp", &lo, -8.f, 0.f); ImGui::SliderFloat("log10 I max##lp", &hi, -3.f, 3.f);
      p.lp_lo = lo; p.lp_hi = std::max<double>(hi, lo + 0.5);
      ImGui::TextDisabled("X-ray view: reflected light of a point corona (Wilkins & Fabian 2012). Bolometric, false colour; the corona is not drawn.");
    }
    if (p.model == 5) {  // dual-cone jet walls: every number is a model choice (the paper's main case: 30 deg, w = 1/128, alpha = 5)
      float tc = float(p.cone_theta_deg), al = float(p.cone_alpha), lo = float(p.cone_lo), hi = float(p.cone_hi);
      ImGui::SliderFloat("cone half-angle [deg]", &tc, 5.f, 80.f); ImGui::SliderFloat("j ~ r^-alpha##cones", &al, 2.f, 8.f);
      ImGui::SliderFloat("log10 I min##cones", &lo, -12.f, -2.f); ImGui::SliderFloat("log10 I max##cones", &hi, -10.f, 2.f);
      p.cone_theta_deg = tc; p.cone_alpha = al; p.cone_lo = lo; p.cone_hi = std::max<double>(hi, lo + 0.5);
      ImGui::TextDisabled("Jet walls near the hole (Papoutsis et al. 2023); optically thin.");
    }
    if (p.model == 4) {  // spherical inflow: flow and emissivity are model choices; the false colour range is display only
      int fl = p.sph_flow; ImGui::Combo("gas", &fl, "free fall from infinity\0at rest (outside the ergoregion)\0"); p.sph_flow = fl;
      float al = float(p.sph_alpha), lo = float(p.sph_lo), hi = float(p.sph_hi);
      ImGui::SliderFloat("j ~ r^-alpha", &al, 2.f, 6.f); ImGui::SliderFloat("log10 I min", &lo, -12.f, -2.f); ImGui::SliderFloat("log10 I max", &hi, -10.f, 0.f);
      p.sph_alpha = al; p.sph_lo = lo; p.sph_hi = std::max<double>(hi, lo + 0.5);
      ImGui::TextDisabled("Bolometric, optically thin (Narayan, Johnson & Gammie 2019).");
    }
    if (p.model == 1 || p.model == 3) { float n = float(std::log10(p.ne0)), be = float(p.plasma_beta), te = float(p.theta_e_max); if (ImGui::SliderFloat("log10 n_e0", &n, 3.f, 7.f)) p.ne0 = std::pow(10.0, n); ImGui::SliderFloat("beta", &be, 0.5f, 30.f); ImGui::SliderFloat("Theta_e max", &te, 5.f, 40.f); p.plasma_beta = be; p.theta_e_max = te; }
    if (p.model == 2) {
      float rh = float(p.rhigh), mu = float(std::log10(p.munit)), tl = float(p.tb_lo), th = float(p.tb_hi);
      if (ImGui::SliderFloat("R_high", &rh, 1.f, 160.f, "%.0f", ImGuiSliderFlags_Logarithmic)) p.rhigh = rh;
      if (ImGui::SliderFloat("log10 M_unit [g]", &mu, 23.f, 27.f)) p.munit = std::pow(10.0, mu);
      float sc = float(p.grmhd_sigma_cut);
      if (ImGui::SliderFloat("sigma cut (0 = off)", &sc, 0.f, 30.f, "%.1f")) p.grmhd_sigma_cut = sc;
      if (ImGui::IsItemHovered()) ImGui::SetTooltip("No emission where sigma = b^2/rho exceeds the cut: the jet funnel, where the density is a numerical floor.\nEHT M87 papers use 1 (10 tested); Chael et al. 2019 used 25.");
      ImGui::SliderFloat("T_b min (log)", &tl, 6.f, 11.f); ImGui::SliderFloat("T_b max (log)", &th, 8.f, 12.f); p.tb_lo = tl; p.tb_hi = std::max<double>(th, tl + 0.5);
      char buf[512]; std::snprintf(buf, sizeof buf, "%s", st.dump_dir.c_str());
      if (ImGui::InputText("dump folder", buf, sizeof buf)) { st.dump_dir = buf; scan_dumps(st); }
      if (st.dump_dir.empty()) { st.dump_dir = bhs_data("/athenak/run_d/bgm_hi"); scan_dumps(st); }
      if (st.dump_scanned != st.dump_dir) { st.dump_scanned = st.dump_dir; scan_dumps(st); }
      if (st.dump_dir_ok) {
        int idx = st.dump_idx; bool ch = ImGui::SliderInt("snapshot", &idx, st.dump_first, st.dump_last);
        ImGui::Checkbox("play", &st.playing); ImGui::SameLine(); ImGui::SetNextItemWidth(120); ImGui::SliderFloat("dumps/s", &st.play_rate, 1.f, 30.f);
        ImGui::Checkbox("interpolate in time (smooth)", &st.dump_blend);
        if (ch) { st.dump_idx = idx; char path[1024]; std::snprintf(path, sizeof path, "%s/mad_%05d.bgm", st.dump_dir.c_str(), idx); rq.load_dump = true; rq.dump_path = path; }
        ImGui::TextDisabled("2 M between snapshots (T600_d); t = %.0f M", 10000.0 + 2.0 * (idx - 200.0));
      } else ImGui::TextColored(ImVec4(0.95f, 0.45f, 0.35f, 1), "no mad_*.bgm dumps in this folder");
    }
    if (p.model == 0 && !p.nodisk) {  // every disk with a surface pattern: each ring turns with the Kerr Omega(r) (inner rings faster)
      ImGui::Checkbox("play disk time", &st.disk_play); ImGui::SameLine(); ImGui::SetNextItemWidth(120); ImGui::SliderFloat("M/s", &st.disk_rate, 1.f, 100.f, "%.0f", ImGuiSliderFlags_Logarithmic);
      float t = float(p.disk_time); if (ImGui::SliderFloat("disk time (M)", &t, 0.f, 2000.f)) p.disk_time = t;
    }
    bool nd2 = p.nodoppler; if (ImGui::Checkbox("no Doppler", &nd2)) p.nodoppler = nd2;
  }

  if (ImGui::CollapsingHeader("Camera and observer", ImGuiTreeNodeFlags_DefaultOpen)) {
    float d = float(cam.dist), th = float(cam.theta_deg), ph = float(cam.phi_deg), fov = float(p.fov_deg);
    double dmin = 1.5, dmax = 2000.0;
    if (!p.wormhole) kcuda::camera_range(p, dmin, dmax, observer); else { dmin = 0.1; dmax = 60.0; }  // wormhole: |l| <= 60 rho, as the position slider and the wheel
    d = float(std::min(std::max(double(d), dmin), dmax)); cam.dist = d; if (p.wormhole && std::fabs(p.wh_lc) > dmax) p.wh_lc = std::copysign(dmax, p.wh_lc);  // never inside the horizon / beyond r_c
    if (ImGui::SliderFloat("distance", &d, float(dmin), float(dmax), "%.2f", ImGuiSliderFlags_Logarithmic | ImGuiSliderFlags_AlwaysClamp)) { cam.dist = d; if (p.wormhole) p.wh_lc = d; }
    if (ImGui::SliderFloat("theta (inclination)", &th, 0.1f, 179.9f)) cam.theta_deg = th;
    if (ImGui::SliderFloat("phi (azimuth)", &ph, 0.f, 360.f)) cam.phi_deg = ph;
    if (ImGui::SliderFloat("FOV", &fov, 2.f, 150.f)) p.fov_deg = fov;
    ImGui::Checkbox("auto-orbit the camera around the hole", &st.orbit_play); ImGui::SameLine(); ImGui::SetNextItemWidth(110); ImGui::SliderFloat("deg/s##orbit", &st.orbit_rate, 1.f, 90.f, "%.0f", ImGuiSliderFlags_Logarithmic | ImGuiSliderFlags_AlwaysClamp);
    if (!p.wormhole && p.charge == 0 && p.lambda == 0) {
      const char* obs[] = {"static", "orbit", "infall"}; int oi = observer == "orbit" ? 1 : observer == "infall" ? 2 : 0;
      if (ImGui::Combo("observer", &oi, obs, 3)) observer = obs[oi];
      if (ImGui::IsItemHovered()) ImGui::SetTooltip("The camera's state of motion, not an animation: static = at rest; orbit = on the circular geodesic at this distance;\ninfall = falling radially from rest at infinity (the frame of someone who dropped in). It changes the aberration and the Doppler shift of the image (and the closest allowed distance).\nTo make the camera circle the hole, tick 'auto-orbit' above (any variant); to actually fly and fall, use 'Fly the ship'.");
    }
  }

  if (ImGui::CollapsingHeader("Image")) {
    float ex = float(std::log10(p.exposure)), sx = float(std::log10(p.sky_exposure)), bl = float(p.bloom);
    if (ImGui::SliderFloat("exposure (log10)", &ex, -1.5f, 1.5f, "%.2f", ImGuiSliderFlags_AlwaysClamp)) p.exposure = std::pow(10.0, ex);
    if (ImGui::SliderFloat("sky exposure (log10)", &sx, -1.f, 1.5f, "%.2f", ImGuiSliderFlags_AlwaysClamp)) p.sky_exposure = std::pow(10.0, sx);
    if (ImGui::SliderFloat("bloom", &bl, 0.f, 0.6f)) p.bloom = bl;
    int tm = int(p.tonemap); if (ImGui::Combo("tone mapping", &tm, "Reinhard\0ACES\0")) p.tonemap = tm ? kcuda::Tonemap::Aces : kcuda::Tonemap::Reinhard;
    bool cin = cinematic; if (ImGui::Checkbox("cinematic finish (aesthetic)", &cin)) rq.toggle_cinematic = true;
    int pr = p.prec == kcuda::Precision::Double ? 1 : 0;
    if (ImGui::Combo("precision", &pr, "float (real time)\0double\0")) { p.prec = pr ? kcuda::Precision::Double : kcuda::Precision::Float; p.tol = pr ? 1e-8 : 2e-5; }
  }

  if (ImGui::CollapsingHeader("Help")) {
    ImGui::TextWrapped("Mouse: drag to orbit the camera; wheel = distance. Everything else is in this panel. Shortcuts: F1 hides it, F flies the ship, Esc quits.");
    ImGui::TextWrapped("The coloured label says what is observed, what is model-dependent, what is hypothetical and what is aesthetic (notes/physics/26-realistic-naked-eye-views.md).");
  }
  ImGui::End();
  return rq;
}

