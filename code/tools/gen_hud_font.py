#!/usr/bin/env python3
"""Generates apps/v3_1-kerr-cuda-ui/hud_font.hpp: monospaced bitmap font (ASCII 32..126, cell 7x13) from the
Liberation Mono Bold (SIL OFL / GPL + font exception) rasterised at 11 px without anti-aliasing. Data only; you do not need to
run this to build. Usage: uv run --with pillow python tools/gen_hud_font.py"""
import sys
from PIL import Image, ImageDraw, ImageFont
FONT = "/usr/share/fonts/liberation/LiberationMono-Bold.ttf"; W, H, SIZE = 7, 13, 11
f = ImageFont.truetype(FONT, SIZE)
rows = []
for c in range(32, 127):
    im = Image.new("1", (W, H), 0)
    d = ImageDraw.Draw(im); d.fontmode = "1"
    d.text((0, 0), chr(c), font=f, fill=1)
    px = im.load()
    rows.append([sum((1 << (W - 1 - x)) for x in range(W) if px[x, y]) for y in range(H)])
out = ["#pragma once", "// Generated by tools/gen_hud_font.py (Liberation Mono Bold 11 px, 1 bit): ASCII 32..126, cell 7x13, bit 6 = left pixel.",
       "#include <cstdint>", "namespace bhs::hud {", f"constexpr int kGlyphW = {W}, kGlyphH = {H};",
       f"constexpr uint8_t kFont[95][{H}] = {{"]
for c, r in zip(range(32, 127), rows):
    out.append("  {" + ",".join(f"0x{v:02x}" for v in r) + f"}},  // '{chr(c) if chr(c) not in '\\\\' else 'backslash'}'")
out += ["};", "}  // namespace bhs::hud", ""]
open("apps/v3_1-kerr-cuda-ui/hud_font.hpp", "w").write("\n".join(out))
for ch in "Rr0g":
    print(ch); [print("".join("#" if v >> (W - 1 - x) & 1 else "." for x in range(W))) for v in rows[ord(ch) - 32]]
