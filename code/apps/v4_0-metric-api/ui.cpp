static void scan_dumps(State& st) {
  namespace fs = std::filesystem;
  st.dump_dir_ok = false; int lo = 1 << 30, hi = -1;
  std::error_code ec;
  if (!st.dump_dir.empty() && fs::is_directory(st.dump_dir, ec))
    for (const auto& e : fs::directory_iterator(st.dump_dir, ec)) {
      const std::string n = e.path().filename().string();
      int k = -1;
      if (std::sscanf(n.c_str(), "mad_%d.bgm", &k) == 1 && k >= 0) { lo = std::min(lo, k); hi = std::max(hi, k); }
    }
  if (hi >= 0) { st.dump_first = lo; st.dump_last = hi; st.dump_dir_ok = true; st.dump_idx = std::min(std::max(st.dump_idx, lo), hi); }
}

// Animations advance every frame, also while the panel is hidden (F1): only the widgets live in the panel.
static void advance(State& st, kcuda::Params& p, Camera& cam, const std::string& observer, double dt, Request& rq) {
  if (st.dump_scanned != st.dump_dir) { st.dump_scanned = st.dump_dir; scan_dumps(st); }
  if (p.model == 0 && !p.nodisk && st.disk_play) p.disk_time += double(st.disk_rate) * dt;
  if (st.orbit_play) cam.phi_deg = std::fmod(cam.phi_deg + double(st.orbit_rate) * dt, 360.0);  // auto-orbit: the camera circles the hole (every variant, also the wormhole)
  if (p.model == 2 && st.dump_dir_ok && st.playing) {
    st.play_acc += dt * st.play_rate; int idx = st.dump_idx; bool ch = false;
    while (st.play_acc >= 1.0) { st.play_acc -= 1.0; idx = idx >= st.dump_last ? st.dump_first : idx + 1; ch = true; }
    if (st.dump_blend && idx < st.dump_last) { rq.blend = true; rq.blend_idx = idx; rq.blend_tau = st.play_acc; st.dump_idx = idx; ch = false; }  // loop: snapshot idx and idx+1, tau = fraction
    if (ch) { st.dump_idx = idx; char path[1024]; std::snprintf(path, sizeof path, "%s/mad_%05d.bgm", st.dump_dir.c_str(), idx); rq.load_dump = true; rq.dump_path = path; }
  }
}

