  IMGUI_CHECKVERSION();
  ImGui::CreateContext();
  ImGuiIO& io = ImGui::GetIO();
  io.IniFilename = nullptr;  // no layout file
  ImGui::StyleColorsDark();
  ImGui::GetStyle().WindowRounding = 4.f; ImGui::GetStyle().Alpha = 0.95f;
  // crisp text: a TrueType font (Roboto Medium, compiled in) at the monitor's content scale instead of the 13 px bitmap font
  float xs = 1.f, ys = 1.f; glfwGetWindowContentScale(win, &xs, &ys);
  const float dpi = std::max(1.f, std::max(xs, ys));
  ImFontConfig fc; fc.FontDataOwnedByAtlas = false;  // static array: the atlas must not free it
